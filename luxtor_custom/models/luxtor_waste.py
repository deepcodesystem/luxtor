    @api.depends('width_m', 'height_m', 'product_id')
    def _compute_name(self):
        for r in self:
            W = float(r.width_m or 0.0)
            H = float(r.height_m or 0.0)

            if W and H:
                # Name based on the generated waste dimensions
                r.name = REMNANT_FMT.format(w=W, h=H)
            else:
                # Fallback: product name or generic label
                r.name = r.product_id.display_name or _("Waste")


    # ------------------------------------------------------------------
    # UTILITIES
    # ------------------------------------------------------------------
    def _compute_linear_qty(self, roll_width_m):
        self.ensure_one()
        roll_width_m = float(roll_width_m or 0.0)
        if roll_width_m <= 0:
            return 0.0
        area = max(self.width_m or 0.0, 0.0) * max(self.height_m or 0.0, 0.0)
        if area <= 0.0:
            return 0.0
        return area / roll_width_m

    def _get_roll_width_from_product(self, product):
        tmpl = product.product_tmpl_id
        roller_tags = getattr(tmpl, 'roller_width_ids', False)
        if roller_tags:
            vals = [float(getattr(t, 'value_cm', 0.0) or 0.0) for t in roller_tags]
            vals = [v for v in vals if v > 0]
            width_cm = max(vals) if vals else float(getattr(tmpl, 'width_cm', 0.0) or 0.0)
        else:
            width_cm = float(getattr(tmpl, 'width_cm', 0.0) or 0.0)
        return width_cm / 100.0 if width_cm else 0.0

    # ------------------------------------------------------------------
    # Manual processing button for remnant / roll_end / scrap
    # ------------------------------------------------------------------
    def action_process_waste(self):
        StockMove = self.env['stock.move'].sudo()
        StockMoveLine = self.env['stock.move.line'].sudo()
        StockScrap = self.env['stock.scrap'].sudo()
        Lot = self.env['stock.lot'].sudo()
        Location = self.env['stock.location'].sudo()
        Warehouse = self.env['stock.warehouse'].sudo()

        scrap_loc = self.env.ref(
            'stock.stock_location_scrapped',
            raise_if_not_found=False
        )
        stock_loc = self.env.ref(
            'stock.stock_location_stock',
            raise_if_not_found=False
        )

        # Fallbacks for scrap location
        if not scrap_loc:
            scrap_loc = Location.search(
                [('usage', '=', 'inventory'), ('name', 'ilike', 'scrap')],
                limit=1,
            )
        if not scrap_loc:
            wh = Warehouse.search([], limit=1)
            vals = {
                'name': 'Scrap',
                'usage': 'inventory',
            }
            if wh and wh.view_location_id:
                vals['location_id'] = wh.view_location_id.id
            scrap_loc = Location.create(vals)

        for waste in self:
            debug = []
            debug.append(
                "[WASTE DEBUG] Start action_process_waste for Waste %s (type=%s, initial=%s)"
                % (waste.name or 'N/A', waste.waste_type, waste.initial_waste_type or 'n/a')
            )

            if waste.move_id or waste.scrap_id:
                debug.append("[WASTE DEBUG] Waste already processed -> skip.")
                waste.message_post(body="  | ".join(debug))
                continue

            product = waste.product_id
            if not product:
                debug.append("[WASTE DEBUG] No product -> abort.")
                waste.message_post(body="  | ".join(debug))
                continue

            roll_width_m = waste._get_roll_width_from_product(product)
            debug.append(
                "[WASTE DEBUG] Roll width from product: %.4f m" % roll_width_m
            )
            if not roll_width_m:
                debug.append("[WASTE DEBUG] Roll width = 0 -> abort.")
                waste.message_post(body="  | ".join(debug))
                continue

            qty_lm = waste._compute_linear_qty(roll_width_m)
            debug.append(
                "[WASTE DEBUG] Computed linear qty from width=%.4f, height=%.4f -> qty_lm=%.4f"
                % (waste.width_m or 0.0, waste.height_m or 0.0, qty_lm)
            )

            # Scrap: only require non-zero dimensions
            if waste.waste_type == 'scrap':
                if (waste.width_m or 0.0) <= 0.0 or (waste.height_m or 0.0) <= 0.0:
                    debug.append("[WASTE DEBUG] Scrap with zero width/height -> abort.")
                    waste.message_post(body="  | ".join(debug))
                    continue
            else:
                if qty_lm <= 0:
                    debug.append("[WASTE DEBUG] qty_lm <= 0 -> abort.")
                    waste.message_post(body="  | ".join(debug))
                    continue

            # Lot / Roll
            lot = waste.lot_id
            if not lot:
                seq = waste.env['ir.sequence'].sudo().next_by_code('luxtor.waste.lot') or False
                lot_name = seq or ("LOT-%05d" % waste.id)
                lot = Lot.create({
                    "name": lot_name,
                    "product_id": product.id,
                })
                waste.lot_id = lot
                debug.append(
                    "[WASTE DEBUG] Created new lot: %s (id=%s)" % (lot.name, lot.id)
                )
            else:
                debug.append(
                    "[WASTE DEBUG] Using existing lot: %s (id=%s)" % (lot.name, lot.id)
                )

            # ----------------------------------------------------------
            # SCRAP: create move WH/Stock -> Scrap + stock.scrap(done)
            # ----------------------------------------------------------
            if waste.waste_type == 'scrap':
                # Force source WH/Stock when possible
                if stock_loc:
                    source_loc = stock_loc
                    debug.append(
                        "[WASTE DEBUG] Scrap source forced to WH/Stock: %s (id=%s)"
                        % (source_loc.display_name, source_loc.id)
                    )
                else:
                    source_loc = product.property_stock_production or \
                        product.property_stock_inventory
                    if source_loc:
                        debug.append(
                            "[WASTE DEBUG] Scrap source fallback: %s (id=%s)"
                            % (source_loc.display_name, source_loc.id)
                        )

                if not source_loc or not scrap_loc:
                    debug.append("[WASTE DEBUG] No source or scrap location -> abort.")
                    waste.message_post(body="  | ".join(debug))
                    continue

                debug.append(
                    "[WASTE DEBUG] Scrap destination: %s (id=%s)"
                    % (scrap_loc.display_name, scrap_loc.id)
                )

                # Create stock move (out of stock to scrap)
                move = StockMove.create({
                    "name": _("Waste %s (scrap)") % (waste.name or ''),
                    "product_id": product.id,
                    "product_uom": product.uom_id.id,
                    "product_uom_qty": qty_lm,
                    "location_id": source_loc.id,
                    "location_dest_id": scrap_loc.id,
                    "origin": waste.production_id.name or waste.name,
                })
                debug.append(
                    "[WASTE DEBUG] Created scrap move id=%s for qty_lm=%.4f"
                    % (move.id, qty_lm)
                )

                move._action_confirm()
                move._action_assign()

                if hasattr(move, "quantity_done"):
                    move.quantity_done = qty_lm
                    if move.move_line_ids:
                        move.move_line_ids.write({'lot_id': lot.id})
                else:
                    StockMoveLine.create({
                        "move_id": move.id,
                        "product_id": product.id,
                        "product_uom_id": product.uom_id.id,
                        "location_id": source_loc.id,
                        "location_dest_id": scrap_loc.id,
                        "qty_done": qty_lm,
                        "lot_id": lot.id,
                    })

                move._action_done()
                debug.append("[WASTE DEBUG] Scrap move %s done." % move.id)

                company = waste.production_id.company_id or product.company_id or self.env.company

                scrap_vals = {
                    "name": waste.name or False,                # <<< NEW: scrap gets same name as waste
                    "product_id": product.id,
                    "scrap_qty": qty_lm,
                    "product_uom_id": product.uom_id.id,
                    "location_id": source_loc.id,
                    "scrap_location_id": scrap_loc.id,
                    "origin": waste.production_id.name or waste.name,
                    "company_id": company.id,
                    "lot_id": lot.id,
                    "luxtor_waste_id": waste.id,
                    "lx_width_m": waste.width_m,
                    "lx_height_m": waste.height_m,
                    "lx_area_m2": waste.area_m2,
                }
                scrap = StockScrap.create(scrap_vals)
                debug.append(
                    "[WASTE DEBUG] Created stock.scrap id=%s (draft) for qty_lm=%.4f"
                    % (scrap.id, qty_lm)
                )

                # Mark scrap as done and link move
                try:
                    scrap.write({
                        "state": "done",
                        "date_done": fields.Datetime.now(),
                    })
                    if hasattr(scrap, "move_ids"):
                        scrap.write({"move_ids": [(4, move.id)]})
                    debug.append(
                        "[WASTE DEBUG] Scrap %s marked done and linked to move %s."
                        % (scrap.id, move.id)
                    )
                except Exception as e:
                    debug.append(
                        "[WASTE DEBUG] Warning: unable to link scrap to move: %s" % e
                    )

                waste.scrap_id = scrap.id
                waste.move_id = move.id
                waste.qty = qty_lm
                waste.is_consumed = True
                waste.location_id = scrap_loc

                if not waste.initial_waste_type or waste.initial_waste_type not in ('roll_end', 'scrap'):
                    waste.initial_waste_type = 'scrap'

                waste.message_post(body="  | ".join(debug))
                continue

            # ----------------------------------------------------------
            # REMNANT / ROLL END -> stock.move
            # ----------------------------------------------------------
            treasure = Location.search([('is_lx_treasure', '=', True)], limit=1)
            if not treasure:
                wh = Warehouse.search([], limit=1)
                vals = {
                    'name': 'Treasure',
                    'usage': 'internal',
                    'is_lx_treasure': True,
                }
                if wh and wh.view_location_id:
                    vals['location_id'] = wh.view_location_id.id
                treasure = Location.create(vals)
            debug.append(
                "[WASTE DEBUG] Using Treasure location: %s (id=%s)"
                % (treasure.display_name, treasure.id)
            )

            if waste.waste_type == 'remnant':
                if waste.production_id and waste.production_id.location_dest_id:
                    source_loc = waste.production_id.location_dest_id
                    debug.append(
                        "[WASTE DEBUG] Remnant source from MO dest: %s (id=%s)"
                        % (source_loc.display_name, source_loc.id)
                    )
                else:
                    source_loc = stock_loc or \
                        product.property_stock_production or \
                        product.property_stock_inventory
                    debug.append(
                        "[WASTE DEBUG] Remnant source fallback: %s (id=%s)"
                        % (source_loc.display_name, source_loc.id)
                    )
                dest_loc = waste.location_id or treasure
                if dest_loc.usage != 'internal':
                    dest_loc = treasure
                debug.append(
                    "[WASTE DEBUG] Remnant destination: %s (id=%s)"
                    % (dest_loc.display_name, dest_loc.id)
                )
            else:
                # roll_end
                source_loc = stock_loc or \
                    product.property_stock_production or \
                    product.property_stock_inventory
                dest_loc = treasure
                debug.append(
                    "[WASTE DEBUG] Roll end movement: %s -> %s"
                    % (
                        source_loc.display_name if source_loc else "n/a",
                        dest_loc.display_name,
                    )
                )

            if not source_loc or not dest_loc:
                debug.append("[WASTE DEBUG] Missing source or destination -> abort.")
                waste.message_post(body="  | ".join(debug))
                continue

            move = StockMove.create({
                "name": _("Waste %s (%s)") % (waste.name or '', waste.waste_type),
                "product_id": product.id,
                "product_uom": product.uom_id.id,
                "product_uom_qty": qty_lm,
                "location_id": source_loc.id,
                "location_dest_id": dest_loc.id,
                "origin": waste.production_id.name or waste.name,
            })
            debug.append(
                "[WASTE DEBUG] Created stock.move id=%s for qty_lm=%.4f"
                % (move.id, qty_lm)
            )

            move._action_confirm()
            move._action_assign()

            if hasattr(move, "quantity_done"):
                move.quantity_done = qty_lm
                if move.move_line_ids:
                    move.move_line_ids.write({'lot_id': lot.id})
            else:
                StockMoveLine.create({
                    "move_id": move.id,
                    "product_id": product.id,
                    "product_uom_id": product.uom_id.id,
                    "location_id": source_loc.id,
                    "location_dest_id": dest_loc.id,
                    "qty_done": qty_lm,
                    "lot_id": lot.id,
                })

            move._action_done()
            debug.append("[WASTE DEBUG] Move %s done." % move.id)

            waste.move_id = move.id
            waste.qty = qty_lm

            if not waste.initial_waste_type:
                waste.initial_waste_type = waste.waste_type

            if waste.waste_type == 'roll_end':
                waste.location_id = dest_loc
                debug.append(
                    "[WASTE DEBUG] Roll end kept as 'roll_end' but physically moved to Treasure."
                )

            waste.message_post(body="  | ".join(debug))

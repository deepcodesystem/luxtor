class LuxtorWaste(models.Model):
    """
    Each record represents ONE piece of fabric waste:
      - remnant: usable piece stored in WH/Treasure
      - roll_end: end of roll stored in WH/Treasure (then converted to remnant)
      - scrap: unusable piece moved to scrap location through stock.scrap

    Quantity is stored in LINEAR METERS (not m²).
    """
    _name = 'luxtor.waste'
    _description = 'Roller Fabric Waste / Remnants'
    _order = 'create_date desc'
    _inherit = ['mail.thread', 'mail.activity.mixin']

    # ------------------------------------------------------------------
    # DEFAULTS
    # ------------------------------------------------------------------
    @api.model
    def _default_treasure_location(self):
        """Pick the first Treasure Location as default, if any."""
        loc = self.env['stock.location'].search(
            [('is_lx_treasure', '=', True)], limit=1
        )
        return loc.id if loc else False

    @api.model
    def _default_stock_location(self):
        loc = self.env.ref('stock.stock_location_stock', raise_if_not_found=False)
        return loc.id if loc else False

